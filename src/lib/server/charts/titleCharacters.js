function drawable(codePoint) {
  let low = 0, high = TITLE_CHARACTER_RANGES.length - 1;
  while (low <= high) {
    const mid = (low + high) >> 1;
    const [start, end] = TITLE_CHARACTER_RANGES[mid];
    if (codePoint < start) high = mid - 1;
    else if (codePoint > end) low = mid + 1;
    else return true;
  }
  return false;
}

/** The distinct characters of `text` the chart font cannot draw, in order of appearance. */
export function undrawableTitleCharacters(text) {
  const missing = [];
  for (const char of String(text ?? '')) {
    if (!drawable(char.codePointAt(0)) && !missing.includes(char)) missing.push(char);
  }
  return missing;
}
